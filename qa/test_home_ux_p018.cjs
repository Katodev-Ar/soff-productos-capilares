/** Pruebas estáticas offline P018: navegación, accesibilidad y promesas comerciales. */
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const root = path.resolve(__dirname, '..')
const read = (file) => fs.readFileSync(path.join(root, file), 'utf8')
const home = read('src/app/page.tsx')
const carousel = read('src/components/AutoCarousel.tsx')
const layout = read('src/app/layout.tsx')

assert.match(home, /getAvailableStock\(product\) > 0 && getRolePrice\(product, userRole\) > 0/)
assert.match(home, /\{ id: 'disponibles', label: 'En stock' \}/)
assert.doesNotMatch(home, /Ofertas Únicas|Fravega-style|fallbackOffers/)
assert.match(home, /Descubrí productos SOFF/)
assert.match(home, /aria-pressed=\{activeTab === tab.id\}/)
assert.match(home, /const navigationCategories = useMemo/)
assert.match(home, /encodeURIComponent\(name\)/)
assert.match(home, /\{image \? \(/)
assert.match(home, /<PackageSearch size=\{26\}/)
assert.match(carousel, /prefers-reduced-motion: reduce/)
assert.match(carousel, /hasFocus \|\| prefersReducedMotion/)
assert.match(carousel, /document.hidden/)
assert.match(carousel, /group-focus-within:opacity-100/)
assert.match(carousel, /aria-roledescription="carrusel"/)
assert.match(layout, /Tienda online en Tucumán/)
console.log('SOFF P018: 15 controles estáticos de UX aprobados.')
