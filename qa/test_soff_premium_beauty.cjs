const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const root = path.resolve(__dirname, '..')
const read = file => fs.readFileSync(path.join(root, file), 'utf8')
const page = read('src/app/page.tsx')
const header = read('src/components/Header.tsx')
const card = read('src/components/ProductCard.tsx')
const css = read('src/app/globals.css')
let checks = 0
function yes(condition, label) { assert.ok(condition, label); checks++ }
function has(s, text, label=text) {yes(s.includes(text), label)}
function no(s, text, label=text) {yes(!s.includes(text), label)}

has(page, 'soff-premium-beauty')
has(page, 'premium-hero')
has(page, 'premium-banner')
has(page, 'premium-editorial')
has(page, 'premium-button-gold')
has(page, 'Belleza que se siente.')
has(page, 'Descubrí productos SOFF')
has(page, 'getAvailableStock(product) > 0 && getRolePrice(product, userRole) > 0')
has(page, 'href={`/productos?categoria=${encodeURIComponent(name)}`}')
has(page, 'soff_catalog_public')
has(page, 'safeCombos')
has(page, 'href="/productos"')
has(page, 'banners.length > 0')
has(page, 'getRolePrice(product, userRole)')
no(page, '.from(\'products\')', 'No usar tabla privada de productos para combos')
no(page, 'Accept both changes', 'Sin marcas de resolución')
has(header, 'bg-[#101a23]')
has(header, 'Ver favoritos')
has(header, 'setIsCartOpen(true)')
has(header, 'router.push(term ?')
has(header, 'userRole === \'admin\'')
has(header, 'group-focus-within:visible')
has(card, 'soff-product-card')
has(card, 'getAvailableStock(product)')
has(card, 'hasSellablePrice(product, userRole)')
has(card, 'disabled={!isAvailable}')
has(card, 'addToCart({')
has(card, 'toggleFavorite(product.id)')
has(css, 'prefers-reduced-motion')
has(css, '.premium-editorial')
has(css, '.premium-display')
has(css, '.premium-button-gold')
has(css, '--soff-cyan: #2ac5e8')
console.log(`SOFF P019: ${checks} comprobaciones de diseño e integridad aprobadas.`)
