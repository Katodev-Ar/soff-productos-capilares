const assert=require('node:assert/strict')
const fs=require('node:fs')
const path=require('node:path')
const read=p=>fs.readFileSync(path.resolve(__dirname,'..',p),'utf8')
let checks=0
const ok=(predicate,description)=>{assert.ok(predicate,description);checks++}
const themes=read('src/lib/storefrontTheme.ts')
const admin=read('src/app/admin/apariencia/page.tsx')
const api=read('src/app/api/admin/appearance/route.ts')
const publicApi=read('src/app/api/storefront/theme/route.ts')
const provider=read('src/components/storefront/StorefrontThemeProvider.tsx')
const home=read('src/app/page.tsx'),header=read('src/components/Header.tsx'),card=read('src/components/ProductCard.tsx')
for(const value of ['clasico','premium','perla','aurora']) {
 ok(themes.includes(`'${value}'`),`valor ${value}`)
 ok(admin.includes(`id:'${value}'`),`opción administrador ${value}`)
 ok(home.includes(value==='clasico'?'<HomeClassic />':value==='premium'?'<HomePremium />':value==='perla'?'<HomePerla />':'<HomeAurora />'),`portada ${value}`)
 ok(header.includes(value==='clasico'?'<HeaderClassic />':value==='premium'?'<HeaderPremium />':value==='perla'?'<HeaderPerla />':'<HeaderAurora />'),`encabezado ${value}`)
 ok(card.includes(value==='clasico'?'<ProductCardClassic {...props} />':value==='premium'?'<ProductCardPremium {...props} />':value==='perla'?'<ProductCardPerla {...props} />':'<ProductCardAurora {...props} />'),`tarjeta ${value}`)
}
for(const variant of ['Perla','Aurora']) {
 const h=read(`src/components/storefront/Home${variant}.tsx`)
 ok(h.includes('soff_catalog_public'),`consulta pública ${variant}`)
 ok(h.includes('safeCombos'),`combos seguros ${variant}`)
 ok(h.includes('getAvailableStock(product) > 0 && getRolePrice(product, userRole) > 0'),`filtro stock ${variant}`)
 ok(h.includes('<ProductCard'),`composición de productos ${variant}`)
 ok(h.includes('banners.length > 0'),`banners administrados ${variant}`)
 ok(read(`src/components/storefront/Header${variant}.tsx`).includes(`Header${variant==='Perla'?'Classic':'Premium'}`),`header autenticación ${variant}`)
 ok(read(`src/components/storefront/ProductCard${variant}.tsx`).includes(`ProductCard${variant==='Perla'?'Classic':'Premium'}`),`tarjeta carrito ${variant}`)
}
ok(admin.includes('postAsSoffAdmin'), 'publicación autenticada')
ok(admin.includes('selected===published'), 'evitar publicación innecesaria')
ok(admin.includes('soff_preview='), 'vista previa sin publicar')
ok(api.includes('requireSoffAdmin(req)'), 'endpoint publicación valida admin')
ok(api.includes('isStorefrontTheme(theme)'), 'endpoint valida opción')
ok(api.includes("from('store_settings').upsert"), 'se conserva store_settings')
ok(publicApi.includes('parseStorefrontTheme'), 'GET reconoce nuevos temas')
ok(provider.includes('isStorefrontTheme'), 'provider reconoce nuevos temas')
ok(provider.includes('POLL_INTERVAL_MS'), 'actualización automática')
const css=read('src/app/globals.css')
ok(css.includes('[data-soff-theme="perla"]'), 'estilo perla')
ok(css.includes('[data-soff-theme="aurora"]'), 'estilo aurora')
ok(css.includes('soff-perla-card'), 'tarjetas perla')
ok(css.includes('soff-aurora-card'), 'tarjetas aurora')
console.log(`SOFF P021: ${checks} controles estáticos aprobados.`)
